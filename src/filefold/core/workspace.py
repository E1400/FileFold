from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from .keywords import Category
from .parser import parse
from .splitter import SplitResult, SplitSelection, SubSplitSelection, _sha256, compute_split, split_with_includes

_MANIFEST_DIR = ".filefold"
_MANIFEST_FILE = "workspace.json"


# ---------------------------------------------------------------------------
# Manifest records
# ---------------------------------------------------------------------------

@dataclass
class FileRecord:
    """Hash of a workspace file at the time it was last generated by FileFold."""
    sha256: str
    role: str                  # "mother" | "child" | "grandchild"
    category: str | None = None
    parent: str | None = None  # parent child filename for grandchildren


# ---------------------------------------------------------------------------
# Reimport status
# ---------------------------------------------------------------------------

@dataclass
class ChildStatus:
    filename: str
    category: Category
    changed_in_new_mother: bool  # new content differs from last split
    manually_edited: bool        # file on disk was changed after last split
    new_content: str             # what would be written if regenerated


@dataclass
class ReimportPreview:
    """Result of analysing a new mother file against the current workspace state."""
    new_mother_content: str
    statuses: list[ChildStatus]

    @property
    def safe_to_update(self) -> list[ChildStatus]:
        """Changed in new mother, NOT manually edited — safe to overwrite."""
        return [s for s in self.statuses if s.changed_in_new_mother and not s.manually_edited]

    @property
    def needs_attention(self) -> list[ChildStatus]:
        """Changed in new mother AND manually edited — engineer must decide."""
        return [s for s in self.statuses if s.changed_in_new_mother and s.manually_edited]

    @property
    def unchanged(self) -> list[ChildStatus]:
        """No change in new mother — nothing to do."""
        return [s for s in self.statuses if not s.changed_in_new_mother]


# ---------------------------------------------------------------------------
# Workspace
# ---------------------------------------------------------------------------

@dataclass
class Workspace:
    path: Path
    name: str
    source_name: str
    selections: list[SplitSelection]
    file_records: dict[str, FileRecord] = field(default_factory=dict)
    created_at: str = ""
    updated_at: str = ""

    @property
    def manifest_path(self) -> Path:
        return self.path / _MANIFEST_DIR / _MANIFEST_FILE

    # ------------------------------------------------------------------
    # Persistence
    # ------------------------------------------------------------------

    def _save(self) -> None:
        self.updated_at = datetime.now(timezone.utc).isoformat()
        manifest_dir = self.path / _MANIFEST_DIR
        manifest_dir.mkdir(exist_ok=True)
        data = {
            "name": self.name,
            "source_name": self.source_name,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "selections": [
                {
                    "category": s.category.value,
                    "filename": s.filename,
                    "sub_selections": [
                        {"sub_category": ss.sub_category, "filename": ss.filename}
                        for ss in s.sub_selections
                    ],
                }
                for s in self.selections
            ],
            "file_records": {
                name: {
                    "sha256": r.sha256,
                    "role": r.role,
                    "category": r.category,
                    "parent": r.parent,
                }
                for name, r in self.file_records.items()
            },
        }
        self.manifest_path.write_text(json.dumps(data, indent=2), encoding="utf-8")

    # ------------------------------------------------------------------
    # Constructors
    # ------------------------------------------------------------------

    @classmethod
    def create(
        cls,
        directory: Path,
        source: Path,
        selections: list[SplitSelection],
    ) -> Workspace:
        """Create a new workspace, run initial split, write manifest."""
        directory.mkdir(parents=True, exist_ok=True)
        blocks = parse(source)
        result = split_with_includes(blocks, source, directory, selections)

        now = datetime.now(timezone.utc).isoformat()
        ws = cls(
            path=directory,
            name=directory.name,
            source_name=source.name,
            selections=selections,
            created_at=now,
            updated_at=now,
        )
        ws._record_result(result)
        ws._save()
        return ws

    @classmethod
    def load(cls, directory: Path) -> Workspace:
        """Load an existing workspace from its manifest."""
        manifest = directory / _MANIFEST_DIR / _MANIFEST_FILE
        if not manifest.exists():
            raise FileNotFoundError(f"No FileFold workspace at {directory}")
        data = json.loads(manifest.read_text(encoding="utf-8"))
        return cls(
            path=directory,
            name=data["name"],
            source_name=data["source_name"],
            selections=[
                SplitSelection(
                    Category(s["category"]),
                    s["filename"],
                    sub_selections=[
                        SubSplitSelection(ss["sub_category"], ss["filename"])
                        for ss in s.get("sub_selections", [])
                    ],
                )
                for s in data["selections"]
            ],
            file_records={
                name: FileRecord(
                    sha256=r["sha256"],
                    role=r["role"],
                    category=r.get("category"),
                    parent=r.get("parent"),
                )
                for name, r in data["file_records"].items()
            },
            created_at=data["created_at"],
            updated_at=data["updated_at"],
        )

    # ------------------------------------------------------------------
    # Re-import
    # ------------------------------------------------------------------

    def reimport_preview(self, new_source: Path) -> ReimportPreview:
        """Analyse a new mother file: compute what changed without writing anything."""
        blocks = parse(new_source)
        new_mother_content, new_child_contents = compute_split(blocks, self.selections)

        # Build flat list of all tracked files: children + sub-children
        all_files: list[tuple[str, Category]] = []
        for sel in self.selections:
            all_files.append((sel.filename, sel.category))
            for ss in sel.sub_selections:
                all_files.append((ss.filename, sel.category))

        statuses: list[ChildStatus] = []
        for filename, category in all_files:
            new_content = new_child_contents.get(filename, "")
            new_hash = _sha256(new_content)
            last_hash = self.file_records.get(filename, FileRecord("", "child")).sha256

            current_path = self.path / filename
            current_hash = (
                _sha256(current_path.read_text(encoding="utf-8", errors="surrogateescape"))
                if current_path.exists() else ""
            )

            statuses.append(ChildStatus(
                filename=filename,
                category=category,
                changed_in_new_mother=(new_hash != last_hash),
                manually_edited=(bool(last_hash) and current_hash != last_hash),
                new_content=new_content,
            ))

        return ReimportPreview(new_mother_content=new_mother_content, statuses=statuses)

    def reimport_apply(
        self,
        new_source: Path,
        preview: ReimportPreview,
        filenames_to_update: set[str],
        added_selections: list[SplitSelection] | None = None,
    ) -> None:
        """Write approved child updates, optional new selections, and the new mother file."""
        all_selections = list(self.selections)
        truly_new: list[SplitSelection] = []

        if added_selections:
            existing_cats = {s.category for s in self.selections}
            truly_new = [s for s in added_selections if s.category not in existing_cats]
            all_selections.extend(truly_new)

        # Recompute full split when new selections are added (updates *INCLUDE lines in mother)
        if truly_new:
            blocks = parse(new_source)
            new_mother_content, new_child_contents = compute_split(blocks, all_selections)
        else:
            new_mother_content = preview.new_mother_content
            new_child_contents = {s.filename: s.new_content for s in preview.statuses}

        # Write existing children that were approved
        for status in preview.statuses:
            if status.filename in filenames_to_update:
                content = new_child_contents.get(status.filename, status.new_content)
                if content:
                    (self.path / status.filename).write_text(
                        content, encoding="utf-8", errors="surrogateescape"
                    )
                    self.file_records[status.filename] = FileRecord(
                        sha256=_sha256(content), role="child", category=status.category.value
                    )

        # Write newly added children
        for sel in truly_new:
            content = new_child_contents.get(sel.filename, "")
            if content:
                (self.path / sel.filename).write_text(
                    content, encoding="utf-8", errors="surrogateescape"
                )
                self.file_records[sel.filename] = FileRecord(
                    sha256=_sha256(content), role="child", category=sel.category.value
                )

        if truly_new:
            self.selections = all_selections

        # Always write the new mother using the uploaded filename
        new_name = new_source.name
        (self.path / new_name).write_text(
            new_mother_content, encoding="utf-8", errors="surrogateescape"
        )

        # Clean up old mother file when the filename changed
        if new_name != self.source_name:
            old = self.path / self.source_name
            if old.exists():
                old.unlink()
            self.file_records.pop(self.source_name, None)
            self.source_name = new_name

        self.file_records[new_name] = FileRecord(
            sha256=_sha256(new_mother_content), role="mother"
        )
        self._save()

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _record_result(self, result: SplitResult) -> None:
        self.file_records[result.mother_path.name] = FileRecord(
            sha256=result.mother_sha256, role="mother"
        )
        for child in result.children:
            role = "grandchild" if child.parent else "child"
            self.file_records[child.filename] = FileRecord(
                sha256=child.sha256,
                role=role,
                category=child.category.value if child.category else None,
                parent=child.parent,
            )
